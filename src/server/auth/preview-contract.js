function normalizedHost(value) {
  return String(value || "").trim().toLowerCase();
}

export function isR16StagingHost(value, kind) {
  const host = normalizedHost(value);
  if (!host || host.length > 253 || host.includes("..") || host.includes("/") || host.includes(":")) return false;
  const role = kind === "pooled" ? "-pooler" : "";
  const pattern = new RegExp(`^${R16_STAGING_METADATA.endpoint}${role}\\.[a-z0-9-]+(?:\\.[a-z0-9-]+)+\\.neon\\.tech$`, "u");
  return pattern.test(host);
}

export function previewContractForBranch(branch) {
  return CONTRACTS_BY_BRANCH.get(String(branch || "").trim()) || null;
}

export function isContractDeploymentHost(contract, host) {
  return Boolean(contract) && contract.deploymentHostPattern.test(String(host || "").trim().toLowerCase());
}

export function expectedCommitForContract(contract, env = process.env) {
  if (!contract) return "";
  const value = String(env[contract.expectedCommitEnv] || "").trim().toLowerCase();
  return /^[0-9a-f]{40}$/u.test(value) ? value : "";
}

export function exactPreviewCommit(contract, env = process.env) {
  if (!contract) return false;
  const actual = String(env.VERCEL_GIT_COMMIT_SHA || "").trim().toLowerCase();
  const expected = expectedCommitForContract(contract, env);
  return /^[0-9a-f]{40}$/u.test(actual)
    && !contract.forbiddenCommits.includes(actual)
    && Boolean(expected)
    && actual === expected;
}

/**
 * R54S accepts Vercel CLI Preview deployments without Git metadata. Its
 * only authorized database is the immutable, source-attested R18 Neon branch.
 * This is an identity check, not a database connection.
 */
export function r54sSafePreviewRuntime(env = process.env) {
  if (String(env.VERCEL || '').trim() !== '1') return false;
  if (String(env.VERCEL_ENV || '').trim().toLowerCase() !== 'preview') return false;
  const branch = String(env.VERCEL_GIT_COMMIT_REF || '').trim();
  if (branch && branch !== PREVIEW_CONTRACTS.r54StudentAcceptance.branch) return false;
  if (!trustedPreviewDeploymentHost(PREVIEW_CONTRACTS.r54StudentAcceptance, env)) return false;
  let url;
  try { url = new URL(String(env.DATABASE_URL || '').trim()); }
  catch { return false; }
  if (!['postgres:', 'postgresql:'].includes(url.protocol)) return false;
  if (!url.username || !url.password || url.port && url.port !== '5432') return false;
  if (url.hostname.toLowerCase() !== R18_STAGING_METADATA.pooledHost) return false;
  let database;
  try { database = decodeURIComponent(url.pathname.replace(/^\/+/, '')); }
  catch { return false; }
  if (database !== R18_STAGING_METADATA.database) return false;
  const sslMode = url.searchParams.get('sslmode');
  if (sslMode && sslMode.toLowerCase() !== 'require') return false;
  return true;
}

export function previewContractEnvironment(contract, env = process.env) {
  if (contract === PREVIEW_CONTRACTS.r54StudentAcceptance) return r54sSafePreviewRuntime(env);
  return Boolean(contract)
    && env.VERCEL === "1"
    && String(env.VERCEL_ENV || "").trim().toLowerCase() === "preview"
    && String(env.VERCEL_GIT_COMMIT_REF || "").trim() === contract.branch
    && exactPreviewCommit(contract, env)
    && env[contract.probeEnabledEnv] === "1";
}

export function trustedPreviewDeploymentHost(contract, env = process.env) {
  const raw = String(env?.VERCEL_URL || "").trim();
  if (!raw) return false;
  try {
    const url = new URL(/^https?:\/\//u.test(raw) ? raw : `https://${raw}`);
    return url.protocol === "https:"
      && !url.username
      && !url.password
      && url.pathname === "/"
      && !url.search
      && !url.hash
      && !url.port
      && isContractDeploymentHost(contract, url.hostname);
  } catch {
    return false;
  }
}

export function exactPreviewContractEnvironment(contract, env = process.env) {
  return previewContractEnvironment(contract, env) && trustedPreviewDeploymentHost(contract, env);
}

/**
 * Validate deployment metadata without consulting the attestation flag. This
 * is the read-only bootstrap proof used by the R16 diagnostic route; business
 * access still requires previewContractMetadataAttested().
 */
export function previewContractMetadataConfigured(contract, env = process.env) {
  if (!contract) return false;
  const metadata = contract.metadata;
  const target = contract === PREVIEW_CONTRACTS.r16Staging
    ? R16_STAGING_METADATA
    : (contract === PREVIEW_CONTRACTS.r18Acceptance || contract === PREVIEW_CONTRACTS.r54StudentAcceptance)
      ? R18_STAGING_METADATA
      : contract === PREVIEW_CONTRACTS.cleanIntegration
        ? CLEAN_STAGING_METADATA
        : null;
  if (!target) return false;
  const pooledHost = normalizedHost(env[metadata.pooledHost]);
  const directHost = normalizedHost(env[metadata.directHost]);
  const expectedHosts = contract === PREVIEW_CONTRACTS.r16Staging
    ? R16_STAGING_HOSTS
    : (contract === PREVIEW_CONTRACTS.r18Acceptance || contract === PREVIEW_CONTRACTS.r54StudentAcceptance)
      ? R18_STAGING_HOSTS
      : CLEAN_STAGING_HOSTS;
  const hostsMatch = pooledHost === expectedHosts.pooled && directHost === expectedHosts.direct;
  return env[metadata.project] === target.project
    && env[metadata.branch] === target.branch
    && env[metadata.database] === target.database
    && hostsMatch;
}

/**
 * This is an operator attestation, not a database query. It is deliberately
 * exact and branch-scoped; callers must still perform the independent pooled
 * and direct read-only fingerprints before setting the attestation value.
 */
export function previewContractMetadataAttested(contract, env = process.env) {
  // The R54S source-pinned URL identity replaces operator-supplied metadata.
  if (contract === PREVIEW_CONTRACTS.r54StudentAcceptance) return r54sSafePreviewRuntime(env);
  return previewContractMetadataConfigured(contract, env)
    && env[contract.metadata.attested] === "1";
}

/**
 * Business access is fail-closed only for the new clean Preview contract.
 * Legacy R98 and Production do not consult this gate.
 */
export function isCleanPreviewBusinessAccessBlocked(env = process.env) {
  const isPreview = env.VERCEL === "1"
    && String(env.VERCEL_ENV || "").trim().toLowerCase() === "preview";
  if (!isPreview) return false;
  const contract = previewContractForBranch(env.VERCEL_GIT_COMMIT_REF)
    || (!String(env.VERCEL_GIT_COMMIT_REF || '').trim() && r54sSafePreviewRuntime(env)
      ? PREVIEW_CONTRACTS.r54StudentAcceptance : null);
  // An unknown branch still fails closed. Only R54S with a verified R18
  // database URL may use Vercel CLI's absent Git branch metadata.
  if (!contract) return true;
  // Preserve the explicitly grandfathered legacy R98 contract.
  if (contract.businessGate !== true) return false;
  return !exactPreviewContractEnvironment(contract, env)
    || !previewContractMetadataAttested(contract, env);
}

export function cleanPreviewGateResponse(res, env = process.env) {
  if (!isCleanPreviewBusinessAccessBlocked(env)) return true;
  res.statusCode = 503;
  res.setHeader("Content-Type", "application/json; charset=utf-8");
  res.setHeader("Cache-Control", "no-store");
  res.setHeader("X-Content-Type-Options", "nosniff");
  res.end(JSON.stringify({ error: "CLEAN_PREVIEW_RUNTIME_UNVERIFIED" }));
  return false;
}

