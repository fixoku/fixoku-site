import assert from 'node:assert/strict';
import {captureOrderProductCosts} from '../src/server/domain/r410-order-cost-hook.js';
const orderId='11111111-1111-4111-8111-111111111111';
const itemId='22222222-2222-4222-8222-222222222222';
const productId='33333333-3333-4333-8333-333333333333';
const calls=[];
const db={async query(q,params){calls.push([q,params]);
 if(q.includes('to_regclass'))return {rows:[{ready:true}]};
 if(q.includes('from public.order_items oi')||q.includes('from public.trainer_package_order_items oi'))return {rows:[{orderItemId:itemId,productId,quantity:2}]};
 if(q.includes('from public.physical_products p')&&q.includes('r410_product_cost_versions'))return {rows:[{id:productId,product_type:'PHYSICAL',version:1,unit_cost_minor:12500}]};
 if(q.includes('from public.r410_order_product_cost_snapshots'))return {rows:[]};
 return {rows:[]};}};
assert.equal((await captureOrderProductCosts(db,'STUDENT_ORDER',orderId,{enabled:false})).status,'DISABLED');
assert.equal(calls.length,0);console.log('FEATURE_OFF_NO_QUERIES=PASS');
let a=await captureOrderProductCosts(db,'STUDENT_ORDER',orderId,{enabled:true});
assert.deepEqual({status:a.status,total:a.totalCostMinor},{status:'COMPLETE',total:25000});
assert.ok(calls.some(([q])=>q.includes('r6_order_component_snapshots')));
console.log('STUDENT_ORDER_COST_SNAPSHOT=PASS');
calls.length=0;
a=await captureOrderProductCosts(db,'TRAINER_PACKAGE_ORDER',orderId,{enabled:true});
assert.equal(a.totalCostMinor,25000);
assert.ok(calls.some(([q])=>q.includes('trainer_package_order_items')));
console.log('TRAINER_ORDER_COST_SNAPSHOT=PASS');
const missing={async query(q){if(q.includes('to_regclass'))return {rows:[{ready:false}]};throw Error('unexpected');}};
await assert.rejects(()=>captureOrderProductCosts(missing,'STUDENT_ORDER',orderId,{enabled:true}),e=>e.code==='R410_COST_MIGRATION_REQUIRED');
console.log('MIGRATION_MISSING_FAIL_CLOSED=PASS');
const unknown={async query(q){if(q.includes('to_regclass'))return {rows:[{ready:true}]};if(q.includes('from public.order_items oi'))return {rows:[{orderItemId:itemId,productId,quantity:1}]};if(q.includes('from public.physical_products p'))return {rows:[{id:productId,product_type:'SOFTWARE',version:null,unit_cost_minor:null}]};return {rows:[]};}};
a=await captureOrderProductCosts(unknown,'STUDENT_ORDER',orderId,{enabled:true});
assert.equal(a.status,'INCOMPLETE');assert.equal(a.totalCostMinor,null);
console.log('UNKNOWN_SOFTWARE_COST_NOT_ZERO=PASS');
await assert.rejects(()=>captureOrderProductCosts(db,'BAD_ORDER',orderId,{enabled:true}),e=>e.code==='COST_ORDER_INVALID');
console.log('ORDER_ID_AND_KIND_GUARD=PASS');
console.log('R410_D8G_ORDER_HOOK_OFFLINE=PASS');
