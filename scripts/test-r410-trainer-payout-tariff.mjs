import assert from 'node:assert/strict';
import {validateOwnerPayoutTariff,quoteOwnerPayout,confirmOwnerPayout} from '../src/server/domain/r410-trainer-payout-tariff.js';
const id=(n)=>`${String(n).padStart(8,'0')}-1111-4111-8111-111111111111`;
const tariff={version:1,individualMinor:500000,groupMinor:[400000,300000,200000,150000,100000]};
const context={tariff,mode:'GROUP',trainerId:id(1),studentId:id(2),assignmentId:id(3),classId:id(4)};
assert.deepEqual(Array.from({length:5},(_,n)=>quoteOwnerPayout({...context,activeStudentCount:n}).amountMinor),tariff.groupMinor);
console.log('GROUP_FIVE_SEAT_TARIFF=PASS');
const q=quoteOwnerPayout({...context,activeStudentCount:3});
assert.equal(q.displayText,'4. öğrenci için tanımlanan hakediş');
assert.equal(q.amountMinor,150000);
console.log('APPROVED_TURKISH_LABEL=PASS');
const ownerId=id(5);
assert.equal(confirmOwnerPayout({approvedQuote:q,currentQuote:q,ownerApproved:true,ownerId}).amountMinor,150000);
console.log('OWNER_APPROVAL=PASS');
assert.throws(()=>confirmOwnerPayout({approvedQuote:q,currentQuote:q,ownerApproved:false,ownerId}),/R410_OWNER_APPROVAL_REQUIRED/);
assert.throws(()=>confirmOwnerPayout({approvedQuote:q,currentQuote:quoteOwnerPayout({...context,activeStudentCount:2}),ownerApproved:true,ownerId}),/R410_PAYOUT_STALE_QUOTE/);
assert.throws(()=>confirmOwnerPayout({approvedQuote:q,currentQuote:quoteOwnerPayout({...context,activeStudentCount:3,tariff:{...tariff,version:2}}),ownerApproved:true,ownerId}),/R410_PAYOUT_STALE_QUOTE/);
console.log('UNAPPROVED_AND_STALE_BLOCKED=PASS');
assert.throws(()=>quoteOwnerPayout({...context,activeStudentCount:5}),/R410_CLASS_CAPACITY_INVALID/);
console.log('CAPACITY_FIVE_GUARD=PASS');
const individual=quoteOwnerPayout({...context,mode:'INDIVIDUAL',classId:null,activeStudentCount:0});
assert.equal(individual.amountMinor,500000);
assert.equal(individual.displayText,'Birebir eğitim için tanımlanan hakediş');
console.log('INDIVIDUAL_TARIFF=PASS');
for (const bad of [null,undefined,0,-1,0.5,'1000']) assert.throws(()=>validateOwnerPayoutTariff({...tariff,groupMinor:[bad,1,1,1,1]}));
console.log('INVALID_COST_FAIL_CLOSED=PASS');
const replacement=quoteOwnerPayout({...context,activeStudentCount:2});
assert.equal(replacement.studentOrder,3);
console.log('REPLACEMENT_BASED_ON_ACTIVE_OCCUPANCY=PASS');
console.log('R410_D8_TARIFF_CORE=PASS');